function detectLocale() {
  try {
    const saved = localStorage.getItem(LOCALE_STORAGE_KEY)
    if (saved && MESSAGES[saved]) return saved
  } catch {
    /* localStorage may be unavailable */
  }
  const nav = typeof navigator !== 'undefined' ? navigator.language || '' : ''
  return /^zh/i.test(nav) ? 'zh-CN' : 'en-US'
}

export const locale = ref(detectLocale())

if (typeof document !== 'undefined') document.documentElement.lang = locale.value

/** 取当前语言文案；缺失时回退中文，再回退 key，避免界面出现空白 */
export function t(key, params) {
  const dict = MESSAGES[locale.value] || MESSAGES['zh-CN']
  let text = dict[key] ?? MESSAGES['zh-CN'][key] ?? key
  if (params && typeof text === 'string') {
    text = text.replace(/\{(\w+)\}/g, (placeholder, name) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name] ?? '') : placeholder
    )
  }
  return text
}

/**
 * 切换界面语言：更新响应式 locale，持久化到 localStorage，并通知原生端重建菜单。
 * 初始挂载时可传 persist:false 以避免重复写入。
 */
export function setLocale(next, { persist = true, notifyNative = true } = {}) {
  if (!MESSAGES[next]) return false
  locale.value = next
  if (typeof document !== 'undefined') document.documentElement.lang = next
  try {
    if (persist) localStorage.setItem(LOCALE_STORAGE_KEY, next)
  } catch {
    /* ignore */
  }
  if (notifyNative) {
    try {
      window.mdreader?.setLocale?.(next)?.catch?.(() => {})
    } catch {
      /* 原生端不可用时忽略 */
    }
  }
  return true
}
